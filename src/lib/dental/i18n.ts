const dicts: Record<string, Dict> = {
  en: { ...en, ...wsEn },
  ar: { ...ar, ...wsAr },
  ur: { ...ur, ...wsUr },
};


export function useDentalT() {
  const { default_language } = useCountryConfig();
  const dt = useCallback(
    (key: string, fallback?: string) => {
      const d = dicts[default_language] || en;
      return d[key] || en[key] || fallback || key;
    },
    [default_language]
  );
  const isRTL = ["ar", "ur"].includes(default_language);
  return { dt, isRTL, language: default_language };
}
